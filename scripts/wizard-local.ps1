$workerStartBtn.Add_Click({
  if ($script:workerProcess -and -not $script:workerProcess.HasExited) {
    Append-Log $logBox 'Worker already running.'
    return
  }
  $psi = New-Object System.Diagnostics.ProcessStartInfo
  $psi.FileName = 'cmd.exe'
  $psi.Arguments = '/c pnpm worker:start'
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true

  $script:workerProcess = New-Object System.Diagnostics.Process
  $script:workerProcess.StartInfo = $psi
  $null = $script:workerProcess.Start()
  Append-Log $logBox 'Worker started.'

  $timer = New-Object System.Windows.Forms.Timer
  $timer.Interval = 500
  $timer.Add_Tick({
    if ($script:workerProcess -and -not $script:workerProcess.HasExited) {
      while (-not $script:workerProcess.StandardOutput.EndOfStream) { Append-Log $logBox ($script:workerProcess.StandardOutput.ReadLine()) }
      while (-not $script:workerProcess.StandardError.EndOfStream) { Append-Log $logBox ($script:workerProcess.StandardError.ReadLine()) }
    } else {
      Append-Log $logBox 'Worker exited.'
      $timer.Stop()
      $timer.Dispose()
    }
  })
  $timer.Start()
})

$workerStopBtn.Add_Click({
