function Append-Log {
  param([System.Windows.Forms.TextBox]$LogBox, [string]$Message)
  $timestamp = (Get-Date).ToString('yyyy-MM-dd HH:mm:ss')
  $LogBox.AppendText("[$timestamp] $Message`r`n")
}

function Read-EnvMap {
  param([string]$Path)
  $map = @{}
  if (Test-Path $Path) {
    foreach ($line in Get-Content $Path) {
      if ([string]::IsNullOrWhiteSpace($line) -or $line.Trim().StartsWith('#') -or -not $line.Contains('=')) { continue }
      $idx = $line.IndexOf('=')
      $key = $line.Substring(0, $idx).Trim()
      $value = $line.Substring($idx + 1)
      $map[$key] = $value
    }
  }
  return $map
}

function Write-EnvMap {
  param([string]$Path, [hashtable]$Map)
  $order = @(
    'MOCK_EBAY_MODE', 'EBAY_CLIENT_ID', 'EBAY_CLIENT_SECRET', 'EBAY_MARKETPLACE_ID',
    'EBAY_DELIVERY_COUNTRY', 'EBAY_DELIVERY_POSTAL_CODE', 'TELEGRAM_BOT_TOKEN',
    'TELEGRAM_CHAT_ID', 'DB_PATH', 'DATABASE_URL'
  )
  $lines = New-Object System.Collections.Generic.List[string]
  $lines.Add('# Generated by local wizard')
  foreach ($k in $order) {
    $v = ''
    if ($Map.ContainsKey($k)) { $v = [string]$Map[$k] }
    $lines.Add("$k=$v")
  }
  Set-Content -Path $Path -Value $lines -Encoding UTF8
}

function Invoke-Step {
  param(
    [System.Windows.Forms.TextBox]$LogBox,
    [string]$Label,
    [string]$Command
  )

  Append-Log $LogBox "$Label -> $Command"

  $psi = New-Object System.Diagnostics.ProcessStartInfo
  $psi.FileName = 'cmd.exe'
  $psi.Arguments = "/c $Command"
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true

  $proc = New-Object System.Diagnostics.Process
  $proc.StartInfo = $psi
  $null = $proc.Start()

  while (-not $proc.HasExited) {
    while (-not $proc.StandardOutput.EndOfStream) { Append-Log $LogBox ($proc.StandardOutput.ReadLine()) }
    while (-not $proc.StandardError.EndOfStream) { Append-Log $LogBox ($proc.StandardError.ReadLine()) }
    Start-Sleep -Milliseconds 100
    [System.Windows.Forms.Application]::DoEvents()
  }

  while (-not $proc.StandardOutput.EndOfStream) { Append-Log $LogBox ($proc.StandardOutput.ReadLine()) }
  while (-not $proc.StandardError.EndOfStream) { Append-Log $LogBox ($proc.StandardError.ReadLine()) }

  if ($proc.ExitCode -ne 0) {
    throw "Step failed ($Label), exit code: $($proc.ExitCode)"
  }
}

